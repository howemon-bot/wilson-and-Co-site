"""Write src/imageSizes.ts: the width and height of every photo in public/images,
so project pages can lay out rows before the photos load (macOS: uses sips),
and src/imageVersions.ts: a short code per photo that changes when the photo
changes, so browsers fetch a replaced photo instead of an old saved copy.
Run again after adding or replacing photos:  python3 scripts/image_sizes.py"""
import hashlib, json, pathlib, subprocess

root = pathlib.Path(__file__).resolve().parent.parent
sizes = {}
versions = {}
for f in sorted((root / 'public/images').rglob('*')):
    if f.suffix.lower() not in ('.jpg', '.jpeg', '.png', '.webp'):
        continue
    out = subprocess.run(['sips', '-g', 'pixelWidth', '-g', 'pixelHeight', str(f)], capture_output=True, text=True).stdout
    w = int(out.split('pixelWidth:')[1].split()[0]); h = int(out.split('pixelHeight:')[1].split()[0])
    key = '/' + str(f.relative_to(root / 'public'))
    sizes[key] = [w, h]
    versions[key] = hashlib.md5(f.read_bytes()).hexdigest()[:8]
(root / 'src/imageSizes.ts').write_text(
    '// Generated by scripts/image_sizes.py — width and height of each photo.\n'
    'export const imageSizes: Record<string, [number, number]> = ' + json.dumps(sizes, indent=0) + ';\n')
(root / 'src/imageVersions.ts').write_text(
    '// Generated by scripts/image_sizes.py — a code per photo that changes with the photo.\n'
    'export const imageVersions: Record<string, string> = ' + json.dumps(versions, indent=0) + ';\n')
print(len(sizes), 'photos')
